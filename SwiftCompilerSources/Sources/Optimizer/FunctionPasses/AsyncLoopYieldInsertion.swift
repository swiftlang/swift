import AST
import SIL

/// Inserts executor yields on the back-edges of loops containing suspension
/// points.
///
/// The Swift async calling convention keeps the native stack flat by resuming
/// an async function's caller with a guaranteed tail call. On targets where
/// that tail call cannot be guaranteed (currently WebAssembly without the
/// tail-call feature), IRGen falls back to an ordinary call, so every await
/// that resumes synchronously nests one more native frame. A loop of such
/// awaits therefore grows the native stack once per iteration and eventually
/// overflows it.
///
/// This pass bounds that growth: for every loop that contains a suspension
/// point, it inserts a `Builtin.yieldToCurrentExecutor()` on each back-edge.
/// The builtin suspends the task, re-enqueues it on the executor it is
/// already running on, and returns to the executor's run loop, which unwinds
/// the native stack before the next iteration starts.
///
/// By default the pass only runs on targets that need it; it can be forced on
/// or off with `-enable-async-loop-yield` / `-disable-async-loop-yield`.
let asyncLoopYieldInsertion = FunctionPass(name: "async-loop-yield-insertion") {
  (function: Function, context: FunctionPassContext) in

  guard function.isAsync, context.options.enableAsyncLoopYield else {
    return
  }

  for loop in context.loopTree.loops {
    insertYields(in: loop, function, context)
  }
}

/// Handles `loop` and, recursively, its inner loops.
///
/// Nested loops are handled independently: an inner loop's yield is itself a
/// suspension point, and the outer loop's back-edge gets its own yield.
private func insertYields(in loop: Loop, _ function: Function, _ context: FunctionPassContext) {
  for innerLoop in loop.innerLoops {
    insertYields(in: innerLoop, function, context)
  }

  guard loop.containsSuspensionPoint else {
    return
  }

  for latch in loop.latches {
    insertYieldOnBackEdge(from: latch, to: loop.header, function, context)
  }
}

private func insertYieldOnBackEdge(from latch: BasicBlock, to header: BasicBlock,
                                   _ function: Function, _ context: FunctionPassContext) {
  // SIL has no critical edges, and a loop header always has at least two
  // predecessors, so the back-edge is always an unconditional branch from the
  // latch: the yield can go right before it, and is then executed only when
  // the loop iterates again.
  guard let branch = latch.terminator as? BranchInst, branch.targetBlock == header else {
    assertionFailure("back-edge is not an unconditional branch to the header?")
    return
  }

  // Be idempotent: the pass may run again on already processed SIL (e.g. on
  // functions deserialized from another module).
  if let previous = branch.previous, previous.isYieldToCurrentExecutor {
    return
  }

  let builder = Builder(before: branch, location: branch.location.asAutoGenerated, context)
  let voidType = context.getTupleType(elements: [] as [AST.`Type`]).loweredType(in: function)
  builder.createBuiltin(name: "yieldToCurrentExecutor", type: voidType, arguments: [])
}

private extension Loop {
  /// The blocks of the loop that branch back to the header.
  var latches: LazyFilterSequence<PredecessorList> {
    header.predecessors.lazy.filter { contains(block: $0) }
  }

  var containsSuspensionPoint: Bool {
    loopBlocks.contains { block in
      block.instructions.contains { $0.isSuspensionPoint }
    }
  }
}

private extension Instruction {
  var isYieldToCurrentExecutor: Bool {
    if let builtin = self as? BuiltinInst {
      return builtin.id == .YieldToCurrentExecutor
    }
    return false
  }

  /// Whether this instruction can suspend the current task, i.e. whether
  /// resuming after it may nest a native frame on targets without guaranteed
  /// async tail calls.
  var isSuspensionPoint: Bool {
    switch self {
    case let apply as FullApplySite:
      return apply.isAsync
    case is HopToExecutorInst, is AwaitAsyncContinuationInst:
      return true
    default:
      return isYieldToCurrentExecutor
    }
  }
}
